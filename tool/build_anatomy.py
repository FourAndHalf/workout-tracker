#!/usr/bin/env python3
"""Generates lib/features/explore/widgets/anatomy_paths.g.dart from
react-native-body-highlighter (MIT, (c) 2022 ELABBASSI Hicham).

  npm pack react-native-body-highlighter@3.2.0 && tar xzf react-native-body-highlighter-3.2.0.tgz
  python3 -I tool/build_anatomy.py package/

The package is read as text and never executed. Its licence is kept in
third_party/react-native-body-highlighter/LICENSE and registered with the
app's licence page.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pkg = sys.argv[1]
dist = os.path.join(pkg, "dist")


def muscles(name):
    text = open(os.path.join(dist, "assets", f"{name}.js"), encoding="utf-8").read()
    out = {}
    for block in re.split(r"\n\s*\{\s*\n\s*slug:", text)[1:]:
        slug = re.match(r'\s*"([^"]+)"', block).group(1)
        paths = []
        for side in ("common", "left", "right"):
            m = re.search(side + r":\s*\[(.*?)\]", block, re.S)
            if m:
                paths += re.findall(r'"([^"]+)"', m.group(1))
        out[slug] = paths
    return out


wrapper = open(os.path.join(dist, "components", "SvgMaleWrapper.js"), encoding="utf-8").read()
outline = {
    side: re.search(rf'side === "{side}" && \(<[^>]*? d="([^"]+)"', wrapper).group(1)
    for side in ("front", "back")
}
views = {"front": muscles("bodyFront"), "back": muscles("bodyBack")}


def dart_str(s):
    assert "'" not in s and "$" not in s and "\\" not in s
    return f"'{s}'"


lines = [
    "// GENERATED by tool/build_anatomy.py. Do not edit by hand.",
    "//",
    "// Body outline and muscle shapes from react-native-body-highlighter 3.2.0",
    "// (https://github.com/HichamELBSI/react-native-body-highlighter),",
    "// MIT License, Copyright (c) 2022 ELABBASSI Hicham. The full licence is in",
    "// third_party/react-native-body-highlighter/LICENSE and in the app's",
    "// licence page.",
    "//",
    "// Coordinates: front view in a 724 x 1448 box; back view in the same size",
    "// box offset by x + 724.",
    "// ignore_for_file: lines_longer_than_80_chars",
    "",
    "const anatomyOutline = <String, String>{",
]
for side, d in outline.items():
    lines.append(f"  '{side}': {dart_str(d)},")
lines += ["};", "", "/// view -> muscle slug -> SVG path data (both sides of the body).",
          "const anatomyMuscles = <String, Map<String, List<String>>>{"]
for side, ms in views.items():
    lines.append(f"  '{side}': {{")
    for slug, paths in ms.items():
        lines.append(f"    '{slug}': [")
        for p in paths:
            lines.append(f"      {dart_str(p)},")
        lines.append("    ],")
    lines.append("  },")
lines.append("};")
dest = os.path.join(ROOT, "lib", "features", "explore", "widgets", "anatomy_paths.g.dart")
open(dest, "w").write("\n".join(lines) + "\n")
print("wrote", dest, sum(len(v) for v in views["front"].values()), "+", sum(len(v) for v in views["back"].values()), "paths")
